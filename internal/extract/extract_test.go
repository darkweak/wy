const samplePath = "example.com/sample"

// sampleModule creates a module holding testdata/sample that depends on wy
// itself, the way a user of wy extract would set things up.
func sampleModule(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	src, err := os.ReadFile("testdata/sample/sample.go")
	if err != nil {
		t.Fatal(err)
	}
	gomod := "module example.com/sample\n\ngo " + gocmd.GoDirective() + "\n\nrequire wy v0.0.0\n\nreplace wy => " + root + "\n"
	write(t, filepath.Join(dir, "go.mod"), gomod)
	write(t, filepath.Join(dir, "sample.go"), string(src))
	return dir
}

func write(t *testing.T, path, data string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

func generateSample(t *testing.T, mod string, goos ...string) string {
	t.Helper()
	out := t.TempDir()
	var log bytes.Buffer
	err := Run(context.Background(), Options{
		Packages: []string{samplePath},
		OutDir:   out,
		PkgName:  "wysyms",
		GOOS:     goos,
		Dir:      mod,
		Log:      &log,
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(log.String(), samplePath+": ") {
		t.Errorf("log = %q", log.String())
	}
	data, err := os.ReadFile(filepath.Join(out, "zsym_example_com_sample.go"))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestGenerateSample(t *testing.T) {
	src := generateSample(t, sampleModule(t))
	if _, err := parser.ParseFile(token.NewFileSet(), "z.go", src, 0); err != nil {
		t.Fatalf("generated code does not parse: %v\n%s", err, src)
	}
	// Compare with whitespace collapsed: gofmt aligns map values.
	norm := func(s string) string { return strings.Join(strings.Fields(s), " ") }
	flat := norm(src)
	for _, want := range []string{
		"// Code generated by wy extract; DO NOT EDIT.",
		"package wysyms",
		`"wy/tree/native"`,
		`sample "example.com/sample"`,
		`Path: "example.com/sample"`,
		`"Total":`,
		`reflect.ValueOf(sample.Total)`,
		`reflect.ValueOf(&sample.Counter)`,
		`reflect.TypeFor[sample.Point]()`,
		`reflect.TypeFor[sample.Alias]()`,
		`constant.MakeString(string(sample.Name))`,
		`constant.MakeBool(bool(sample.Enabled))`,
		`constant.MakeInt64(int64(sample.Answer))`,
		`constant.MakeUint64(uint64(sample.Big))`,
		`constant.MakeFromLiteral("1267650600228229401496703205376", native.TokenINT, 0)`,
		`native.Float("13/4")`,
		`constant.MakeImag(native.Float("2"))`,
		`Type: reflect.TypeOf(sample.Typed)`,
		`Untyped: "int"`,
		`Untyped: "float"`,
		`Untyped: "complex"`,
		`"Shape": reflect.TypeFor[_example_com_sample_Shape]()`,
		`"Closer": reflect.TypeFor[_example_com_sample_Closer]()`,
		"func (w _example_com_sample_Shape) Scale(a0 float64, a1 ...string) (sample.Shape, error)",
		`native.As[sample.Shape](r[0])`,
		`w.XWyBox.Call("Reset", nil)`,
	} {
		if !strings.Contains(flat, norm(want)) {
			t.Errorf("generated code lacks %q", want)
		}
	}
	for _, unwanted := range []string{
		`"Map"`, `"Box"`, // generic
		`"internal"`, `"unexported"`, // unexported
		`"Hidden": reflect.TypeFor[_`, `"Empty": reflect.TypeFor[_`, // not wrappable
	} {
		if strings.Contains(flat, norm(unwanted)) {
			t.Errorf("generated code contains %q", unwanted)
		}
	}
	if t.Failed() {
		t.Log(src)
	}
}

// TestGeneratedCodeRuns compiles a host program that links the generated
// symbols and lets the tree interpreter call into the package, including
// with an interpreted implementation of one of its interfaces.
func TestGeneratedCodeRuns(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a program")
	}
	mod := sampleModule(t)
	write(t, filepath.Join(mod, "wysyms", "zsym.go"), generateSample(t, mod))
	write(t, filepath.Join(mod, "cmd", "host", "main.go"), `package main

import (
	"context"
	"fmt"
	"os"

	_ "example.com/sample/wysyms"
	"wy/tree"
)

const prog = `+"`"+`package main

import (
	"errors"
	"fmt"
	"example.com/sample"
)

type square struct{ side float64 }

func (s *square) Area() float64 { return s.side * s.side }
func (s *square) Scale(f float64, names ...string) (sample.Shape, error) {
	if len(names) == 0 {
		return nil, errors.New("no names")
	}
	return &square{s.side * f}, nil
}
func (s *square) Reset() { s.side += 1 }

func main() {
	sample.Counter = 5
	sample.Counter++
	p := sample.Point{X: 1, Y: 2}
	fmt.Println(sample.Name, sample.Enabled, sample.Answer, sample.Pi, sample.Typed, sample.Huge>>99)
	fmt.Println(p.Sum(), sample.Counter, sample.Alias{X: 3}.Sum())
	fmt.Println(sample.Total(&square{2}, &square{3}))
	fmt.Println(sample.Grow(&square{1.5}))
}
`+"`"+`

func main() {
	in := tree.New(tree.Options{})
	if err := in.RunSource(context.Background(), []byte(prog), "prog.go", nil); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
`)
	tmp := t.TempDir()
	bin := filepath.Join(tmp, "host")
	if out, err := gocmd.Run(context.Background(), mod, []string{"GOFLAGS=-mod=mod", "GOWORK=off"},
		"build", "-o", bin, "./cmd/host"); err != nil {
		t.Fatalf("building host: %v\n%s", err, out)
	}
	out, err := exec.Command(bin).CombinedOutput()
	if err != nil {
		t.Fatalf("host: %v\n%s", err, out)
	}
	want := "sample true 42 3.25 L3 2\n3 6 3\n13\n16 <nil>\n"
	if string(out) != want {
		t.Fatalf("output:\n%s\nwant:\n%s", out, want)
	}
}

// TestCommonAcrossGOOS checks that symbols missing on one platform are
// dropped; the sample package has the same API everywhere.
func TestCommonAcrossGOOS(t *testing.T) {
	mod := sampleModule(t)
	one := generateSample(t, mod, "linux")
	all := generateSample(t, mod, "linux", "darwin", "windows")
	if one != all {
		t.Fatalf("platform-independent package differs across GOOS sets:\n%s\n---\n%s", one, all)
	}
}

// TestMatchesCommittedStdlib regenerates a few standard-library tables and
// compares them with the committed files in tree/stdlib, so the generator
// and its output cannot drift apart.
func TestMatchesCommittedStdlib(t *testing.T) {
	for _, pkg := range []string{"container/ring", "errors", "strings", "io"} {
		out := t.TempDir()
		err := Run(context.Background(), Options{
			Packages: []string{pkg},
			OutDir:   out,
			PkgName:  "stdlib",
			GOOS:     []string{"linux", "darwin", "windows"},
			Dir:      ".",
		})
		if err != nil {
			t.Fatal(err)
		}
		name := "zsym_" + strings.NewReplacer("/", "_", ".", "_").Replace(pkg) + ".go"
		got, _ := os.ReadFile(filepath.Join(out, name))
		want, err := os.ReadFile(filepath.Join("../../tree/stdlib", name))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s: regenerated table differs from tree/stdlib/%s (run go generate wy/tree/stdlib)", pkg, name)
		}
	}
}

func TestRunErrors(t *testing.T) {
	err := Run(context.Background(), Options{
		Packages: []string{"wy/no/such/package"},
		OutDir:   t.TempDir(),
		PkgName:  "x",
		GOOS:     []string{"linux"},
		Dir:      ".",
	})
	if err == nil || !strings.Contains(err.Error(), "GOOS=linux") {
		t.Fatalf("err = %v", err)
	}
}

func TestImportAliases(t *testing.T) {
	is := &importSet{byPath: map[string]string{}, used: map[string]bool{}}
	if a := is.alias(newPkg("a/reflect", "reflect")); a != "reflect2" {
		t.Errorf("reflect alias = %q", a)
	}
	if a := is.alias(newPkg("b/x", "x")); a != "x" {
		t.Errorf("x alias = %q", a)
	}
	if a := is.alias(newPkg("c/x", "x")); a != "x2" {
		t.Errorf("second x alias = %q", a)
	}
	if a := is.alias(newPkg("b/x", "x")); a != "x" {
		t.Errorf("repeat x alias = %q", a)
	}
	if a := is.alias(newPkg("n/native", "native")); a != "native2" {
		t.Errorf("native alias = %q", a)
	}
}

func newPkg(path, name string) *types.Package { return types.NewPackage(path, name) }
