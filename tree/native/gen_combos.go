//go:build ignore

// gen_combos writes zcombos.go: wrapper types for every combination of the
// optional methods that the standard library probes for dynamically
// (fmt: String/GoString/Format; errors: Error/Unwrap/Is/As; encoders:
// MarshalJSON/MarshalText). A boxed interpreted value passed to native code
// is wrapped in the combination matching its real method set, so native
// type assertions see exactly the methods the value has.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

type method struct{ key, name, params, call, results, ret string }

var plain = []method{
	{"String", "String", "", "nil", "string", "As[string](r[0])"},
	{"GoString", "GoString", "", "nil", "string", "As[string](r[0])"},
	{"Format", "Format", "f fmt.State, verb rune", "[]any{f, verb}", "", ""},
	{"MarshalJSON", "MarshalJSON", "", "nil", "([]byte, error)", "As[[]byte](r[0]), As[error](r[1])"},
	{"MarshalText", "MarshalText", "", "nil", "([]byte, error)", "As[[]byte](r[0]), As[error](r[1])"},
}

var (
	errM    = method{"Error", "Error", "", "nil", "string", "As[string](r[0])"}
	unwrap1 = method{"Unwrap", "Unwrap", "", "nil", "error", "As[error](r[0])"}
	unwrapN = method{"UnwrapMulti", "Unwrap", "", "nil", "[]error", "As[[]error](r[0])"}
	isM     = method{"Is", "Is", "target error", "[]any{target}", "bool", "As[bool](r[0])"}
	asM     = method{"As", "As", "target any", "[]any{target}", "bool", "As[bool](r[0])"}
)

func main() {
	var sets [][]method
	for mask := 0; mask < 1<<len(plain); mask++ {
		var base []method
		for i, m := range plain {
			if mask&(1<<i) != 0 {
				base = append(base, m)
			}
		}
		sets = append(sets, base)
		for _, u := range []*method{nil, &unwrap1, &unwrapN} {
			for _, is := range []bool{false, true} {
				for _, as := range []bool{false, true} {
					s := append(append([]method{}, base...), errM)
					if u != nil {
						s = append(s, *u)
					}
					if is {
						s = append(s, isM)
					}
					if as {
						s = append(s, asM)
					}
					sets = append(sets, s)
				}
			}
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_combos.go; DO NOT EDIT.\n\npackage native\n\nimport (\n\t\"fmt\"\n\t\"reflect\"\n)\n\n")
	var reg bytes.Buffer
	for _, s := range sets {
		if len(s) == 0 {
			continue
		}
		var keys []string
		for _, m := range s {
			keys = append(keys, m.key)
		}
		name := "combo_" + strings.Join(keys, "_")
		fmt.Fprintf(&b, "type %s struct{ XWyBox Caller }\n\n", name)
		for _, m := range s {
			res := m.results
			fmt.Fprintf(&b, "func (w %s) %s(%s) %s {\n", name, m.name, m.params, res)
			if res == "" {
				fmt.Fprintf(&b, "\tw.XWyBox.Call(%q, %s)\n}\n\n", m.key, m.call)
			} else {
				fmt.Fprintf(&b, "\tr := w.XWyBox.Call(%q, %s)\n\treturn %s\n}\n\n", m.key, m.call, m.ret)
			}
		}
		quoted := make([]string, len(keys))
		for i, k := range keys {
			quoted[i] = fmt.Sprintf("%q", k)
		}
		fmt.Fprintf(&reg, "\t{Type: reflect.TypeFor[%s](), Methods: []string{%s}},\n", name, strings.Join(quoted, ", "))
	}
	b.WriteString("func init() {\n\tCombos = []Combo{\n")
	b.Write(reg.Bytes())
	b.WriteString("\t}\n\tfor _, c := range Combos {\n\t\tRegisterWrapper(c.Type)\n\t}\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("zcombos.go", src, 0o644); err != nil {
		panic(err)
	}
	fmt.Println(len(sets)-1, "combos")
}
