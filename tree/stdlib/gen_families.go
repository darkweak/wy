//go:build ignore

// gen_families writes zfamilies.go: for standard interfaces that callers
// probe for optional methods, a wrapper for every combination of those
// methods (see native.Family). Without them, an interpreted
// http.ResponseWriter passed to compiled code would lose its Flush or
// Hijack method, breaking streaming and WebSocket upgrades.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

type method struct {
	iface  string // the single-method interface declaring it
	name   string
	params string // declaration, a0, a1, ...
	args   string // call arguments, as []any{...} or nil
	result string
	ret    string // return expression from r, or "" for no result
}

type family struct {
	name     string // wrapper name prefix
	base     string
	methods  []method // methods of base
	optional []method
}

var families = []family{
	{
		name: "_net_http_ResponseWriter",
		base: "http.ResponseWriter",
		methods: []method{
			{"", "Header", "", "nil", "http.Header", "native.As[http.Header](r[0])"},
			{"", "Write", "a0 []byte", "[]any{a0}", "(int, error)", "native.As[int](r[0]), native.As[error](r[1])"},
			{"", "WriteHeader", "a0 int", "[]any{a0}", "", ""},
		},
		optional: []method{
			{"http.Flusher", "Flush", "", "nil", "", ""},
			{"http.Hijacker", "Hijack", "", "nil", "(net.Conn, *bufio.ReadWriter, error)",
				"native.As[net.Conn](r[0]), native.As[*bufio.ReadWriter](r[1]), native.As[error](r[2])"},
			{"http.Pusher", "Push", "a0 string, a1 *http.PushOptions", "[]any{a0, a1}", "error", "native.As[error](r[0])"},
			{"io.ReaderFrom", "ReadFrom", "a0 io.Reader", "[]any{a0}", "(int64, error)", "native.As[int64](r[0]), native.As[error](r[1])"},
			{"interface{ Unwrap() http.ResponseWriter }", "Unwrap", "", "nil", "http.ResponseWriter", "native.As[http.ResponseWriter](r[0])"},
			{"http.CloseNotifier", "CloseNotify", "", "nil", "<-chan bool", "native.As[<-chan bool](r[0])"},
		},
	},
	{
		name:    "_io_Reader",
		base:    "io.Reader",
		methods: []method{{"", "Read", "a0 []byte", "[]any{a0}", "(int, error)", "native.As[int](r[0]), native.As[error](r[1])"}},
		optional: []method{
			{"io.WriterTo", "WriteTo", "a0 io.Writer", "[]any{a0}", "(int64, error)", "native.As[int64](r[0]), native.As[error](r[1])"},
		},
	},
	{
		name:    "_io_Writer",
		base:    "io.Writer",
		methods: []method{{"", "Write", "a0 []byte", "[]any{a0}", "(int, error)", "native.As[int](r[0]), native.As[error](r[1])"}},
		optional: []method{
			{"io.ReaderFrom", "ReadFrom", "a0 io.Reader", "[]any{a0}", "(int64, error)", "native.As[int64](r[0]), native.As[error](r[1])"},
		},
	},
}

func main() {
	var b bytes.Buffer
	b.WriteString(`// Code generated by gen_families.go; DO NOT EDIT.

package stdlib

import (
	"bufio"
	"io"
	"net"
	"net/http"
	"reflect"

	"github.com/darkweak/wy/tree/native"
)

`)
	var reg bytes.Buffer
	for _, f := range families {
		var opts []string
		for _, m := range f.optional {
			opts = append(opts, fmt.Sprintf("reflect.TypeFor[%s]()", m.iface))
		}
		fmt.Fprintf(&reg, "\tnative.RegisterFamily(&native.Family{\n\t\tBase:     reflect.TypeFor[%s](),\n\t\tOptional: []reflect.Type{%s},\n\t\tMembers: map[uint]reflect.Type{\n",
			f.base, strings.Join(opts, ", "))
		// Member 0 is the plain wrapper, already generated with the package.
		fmt.Fprintf(&reg, "\t\t\t0: reflect.TypeFor[%s](),\n", f.name)
		for mask := uint(1); mask < 1<<len(f.optional); mask++ {
			name := f.name
			ms := append([]method{}, f.methods...)
			for i, m := range f.optional {
				if mask&(1<<i) != 0 {
					name += "_" + m.name
					ms = append(ms, m)
				}
			}
			fmt.Fprintf(&b, "type %s struct{ XWyBox native.Caller }\n\n", name)
			for _, m := range ms {
				fmt.Fprintf(&b, "func (w %s) %s(%s) %s {\n", name, m.name, m.params, m.result)
				if m.ret == "" {
					fmt.Fprintf(&b, "\tw.XWyBox.Call(%q, %s)\n}\n\n", m.name, m.args)
				} else {
					fmt.Fprintf(&b, "\tr := w.XWyBox.Call(%q, %s)\n\treturn %s\n}\n\n", m.name, m.args, m.ret)
				}
			}
			fmt.Fprintf(&reg, "\t\t\t%d: reflect.TypeFor[%s](),\n", mask, name)
		}
		reg.WriteString("\t\t},\n\t})\n")
	}
	fmt.Fprintf(&b, "func init() {\n%s}\n", reg.String())
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("%v\n%s", err, b.String())
	}
	if err := os.WriteFile("zfamilies.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
